import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { walkHtml } from "./html.js";
import { analyseHtml, classify } from "./site.js";
import { checkSite } from "./site-report.js";

const page = (body: string, head = "") =>
  `<!doctype html><html><head>${head}</head><body>${body}</body></html>`;
const site = (html: string) =>
  checkSite({ source: "file", name: "page.html", html, bytes: html.length });

describe("classify: what a piece of text says, by where it sits", () => {
  it.each([
    ["Chat with our AI assistant", true, "in-chat"],
    ["Hi! I'm a bot.", true, "in-chat"],
    ["Ich bin ein KI-Assistent", true, "in-chat"],
    ["Assistant IA", true, "in-chat"],
    ["Ask our assistant", true, "assistant-only"],
    ["Powered by GPT-5", true, "technology-only"],
    ["Services on this website use AI.", false, "site-wide"],
    ["You are chatting with an AI assistant.", false, "page-text"],
    ["Answers here are generated by AI.", false, "page-text"],
    ["Our AI agents resolve 70% of tickets.", false, null],
    ["Ask our assistant", false, null],
    ["Track your order", true, null],
  ] as const)("%j (in chat: %s) → %s", (text, inChat, kind) => {
    expect(classify(text, { inChat })).toBe(kind);
  });

  it("a link to terms or a policy is terms-only, wherever it sits", () => {
    expect(classify("How we use AI", { inChat: false, linkHref: "/legal/ai-policy" })).toBe(
      "terms-only",
    );
    expect(classify("AI terms", { inChat: true, linkHref: "/terms" })).toBe("terms-only");
  });
});

describe("the HTML reader", () => {
  it("knows which elements each piece of text sits in, and reads scripts raw", () => {
    const events = [
      ...walkHtml(
        '<div id="chat"><p>Hi &amp; welcome</p><br><script>var a = "<b>";</script></div><p>out</p>',
      ),
    ];
    const hi = events.find((e) => e.kind === "text" && e.text === "Hi & welcome");
    expect(hi?.stack.map((e) => e.name)).toEqual(["div", "p"]);
    expect(events.find((e) => e.kind === "raw")).toMatchObject({ text: 'var a = "<b>";' });
    const out = events.findLast((e) => e.kind === "text");
    expect(out?.stack.map((e) => e.name)).toEqual(["p"]);
  });
});

describe("site", () => {
  it("finds the disclosure on the demo page's launcher, and the greeting at the first exchange", () => {
    const html = readFileSync(new URL("../examples/demo-site/index.html", import.meta.url), "utf8");
    const r = site(html);
    expect(r.disclosure).toEqual({
      found: true,
      in_chat_interface: true,
      headline:
        'disclosure found: aria-label of button#chat-launcher: "Open chat with our AI assistant"',
    });
    expect(r.signals.map((s) => [s.kind, s.where, s.timing])).toEqual([
      ["in-chat", "aria-label of button#chat-launcher", "before the first exchange"],
      ["in-chat", 'inline chat setting "greeting"', "at the first exchange"],
      ["assistant-only", "text in div#support-chat.chat-widget", "not known"],
      ["assistant-only", 'inline chat setting "botName"', "before the first exchange"],
      ["site-wide", "page text in p", "before the first exchange"],
      ["terms-only", "link to /legal/ai-policy", "before the first exchange"],
    ]);
    expect(r.expects.map((e) => e.cite)).toEqual([
      "AI Act, Art. 50(1)",
      "AI Act, Art. 50(5)",
      "Commission Guidelines on Article 50, point (38)",
      "Commission Guidelines on Article 50, point (38)",
      "Commission Guidelines on Article 50, point (38)",
    ]);
  });

  it("names chat vendors by script, global and element, and says their greeting was not fetched", () => {
    const r = site(
      page(
        '<df-messenger chat-title="Support (AI agent)" agent-id="x"></df-messenger><script src="https://widget.intercom.io/widget/abc123"></script><script id="ze-snippet" src="https://static.zdassets.com/ekr/snippet.js?key=k"></script>',
      ),
    );
    expect(r.widgets.map((w) => w.id)).toEqual(["dialogflow", "intercom", "zendesk"]);
    expect(r.disclosure.headline).toBe(
      'disclosure found: chat-title of df-messenger: "Support (AI agent)"',
    );
    expect(r.cannot_check[0]).toMatch(/Intercom .* says at the first exchange/);
  });

  it("reads a vendor's inline settings, not a page's JSON data", () => {
    const r = site(
      page(
        `<script>window.voiceflow.chat.load({ verify: { projectID: "p" }, assistant: { title: "Acme helper", description: "An AI assistant that answers billing questions" } });</script>
         <script type="application/ld+json">{"name": "Acme AI agent platform", "description": "AI agents for support"}</script>`,
      ),
    );
    expect(r.widgets.map((w) => w.id)).toEqual(["voiceflow"]);
    expect(r.signals.map((s) => [s.kind, s.where])).toEqual([
      ["in-chat", 'Voiceflow setting "description"'],
      ["assistant-only", 'Voiceflow setting "title"'],
    ]);
  });

  it("does not count an AI company's marketing copy as a disclosure", () => {
    const r = site(
      page(
        "<main><h1>AI agents for support teams</h1><p>Our AI agent resolves 70% of conversations.</p></main>",
      ),
    );
    expect(r.disclosure.found).toBe(false);
    expect(r.disclosure.headline).toMatch(/^no disclosure found in /);
  });

  it("with no chat and no disclosure, says what it read", () => {
    const r = site(page("<p>Shoes and socks.</p>"));
    expect(r.widgets).toEqual([]);
    expect(r.disclosure.headline).toBe(
      "no disclosure found in 77 bytes of HTML, 1 text block, 0 labels, titles and placeholders, 0 inline chat settings",
    );
  });

  it("flags a page drawn by script, which the HTML as served cannot show", () => {
    const r = site(page('<div id="root"></div><script src="/assets/app.js"></script>'));
    expect(r.script_rendered).toBe(true);
    expect(r.cannot_check.join(" ")).toMatch(/save the rendered page/);
  });

  it("counts what it checked", () => {
    expect(analyseHtml(page('<button aria-label="Open chat">x</button>')).checked).toMatchObject({
      attributes: 1,
      textBlocks: 1,
    });
  });
});
